    // MARK: - Shape mutation error path

    func testDeleteShapeOfUnknownIDThrowsShapeNotFoundWithoutPersisting() async throws {
        let layer = try await DrawTestDataLayer.startedOrSkip()
        let store = DrawingStore(dataLayer: layer)
        let drawing = try await store.upsert(Drawing(title: "DeleteShape ErrorPath Gate Test"))
        let unknownShapeID = UUID()

        do {
            _ = try await store.deleteShape(unknownShapeID, for: drawing.id)
            XCTFail("expected DrawingStoreError.shapeNotFound")
        } catch DrawingStoreError.shapeNotFound(let id) {
            XCTAssertEqual(id, unknownShapeID)
        }

        let receipts = try await store.receipts(forDrawing: drawing.id)
        let deleteShapeReceipts = receipts.filter { $0.receiptType == DrawingReceiptType.deleteShape.rawValue }
        XCTAssertEqual(deleteShapeReceipts.count, 0, "a failed shape delete must not append a deleteShape receipt")
    }

    // MARK: - Shape insert: receipt payload keys

    func testInsertShapeEmitsExactlyOneReceiptWithShapeIDAndKind() async throws {
        let layer = try await DrawTestDataLayer.startedOrSkip()
        let store = DrawingStore(dataLayer: layer)
        let drawing = try await store.upsert(Drawing(title: "InsertShape Gate Test"))
        let shape = Shape(kind: .ellipse, geometry: ShapeGeometry(x: 0, y: 0, width: 5, height: 5))

        _ = try await store.insertShape(shape, for: drawing.id)

        let receipts = try await store.receipts(forDrawing: drawing.id)
        let insertReceipts = receipts.filter { $0.receiptType == DrawingReceiptType.insertShape.rawValue }
        XCTAssertEqual(insertReceipts.count, 1)
        XCTAssertEqual(insertReceipts.first?.payload["shapeID"], .string(shape.id.uuidString))
        XCTAssertEqual(insertReceipts.first?.payload["kind"], .string("ellipse"))
    }
